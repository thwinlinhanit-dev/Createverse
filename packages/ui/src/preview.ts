const STRINGS: Readonly<Record<Lang, Strings>> = { en: EN, "zh-Hant": ZH };

function figure(caption: string, body: string): string {
  return `<figure class="pv-field"><figcaption>${escapeHtml(caption)}</figcaption>${body}</figure>`;
}

function componentColumn(lang: Lang): string {
  const s = STRINGS[lang];
  const icons = ICON_NAMES.map(
    (name) =>
      `<span class="pv-icon-demo">${renderIcon({ name, label: s.icons[name] })}` +
      `<span>${escapeHtml(s.icons[name])}</span></span>`,
  ).join("");

  return [
    figure(s.captions["buttonPrimary"] ?? "", renderButton({ label: s.buttonPrimary })),
    figure(s.captions["buttonSecondary"] ?? "", renderButton({ label: s.buttonSecondary, variant: "secondary" })),
    figure(s.captions["buttonDisabled"] ?? "", renderButton({ label: s.buttonDisabled, disabled: true })),
    figure(s.captions["buttonLoading"] ?? "", renderButton({ label: s.buttonLoading, loading: true })),
    figure(s.captions["icons"] ?? "", `<div class="pv-row">${icons}</div>`),
    figure(s.captions["card"] ?? "", renderCard({ label: s.cardTitle, body: s.cardBody })),
    figure(
      s.captions["chip"] ?? "",
      `<div class="pv-row">` +
        renderChip({ label: s.chip }) +
        renderChip({ label: s.chipSelected, selected: true }) +
        `</div>`,
    ),
    figure(s.captions["tabs"] ?? "", renderTabs({ tabs: s.tabs, active: 1 })),
    figure(s.captions["dialog"] ?? "", renderDialog({ label: s.dialogTitle, body: s.dialogBody, open: true })),
    figure(s.captions["stepProgress"] ?? "", renderStepProgress({ current: 2, total: 4, label: s.stepProgress })),
    figure(
      s.captions["hint"] ?? "",
      renderHintButton({ level: 1, label: s.hint, ariaLabel: s.hintAria }),
    ),
    figure(
      s.captions["portfolio"] ?? "",
      renderPortfolioCard({ label: s.portfolioTitle, detail: s.portfolioDetail, date: s.portfolioDate }),
    ),
    figure(
      s.captions["parentGate"] ?? "",
      renderParentGate({ reason: s.parentGateReason, actionLabel: s.parentGateAction }),
    ),
    figure(
      s.captions["safetyInfo"] ?? "",
      renderSafetyNotice({
        severity: "info",
        message: s.safetyInfo,
        nextStep: s.safetyInfoNext,
        severityLabel: s.severityInfo,
      }),
    ),
    figure(
      s.captions["safetyWarning"] ?? "",
      renderSafetyNotice({
        severity: "warning",
        message: s.safetyWarning,
        nextStep: s.safetyWarningNext,
        severityLabel: s.severityWarning,
      }),
    ),
  ].join("\n");
}

/** English-first label pair: English visible by default, Chinese toggled by the language switch. */
function t(en: string, zh: string): string {
  return (
    `<span lang="en" data-lang-block="en">${escapeHtml(en)}</span>` +
    `<span lang="zh-Hant" data-lang-block="zh-Hant" hidden>${escapeHtml(zh)}</span>`
  );
}

function stageHeading(stage: StageName): string {
  return t(EN.stages[stage], ZH.stages[stage]);
}

