const PREVIEW_SCRIPT = `
const stageButtons = Array.from(document.querySelectorAll("[data-set-stage]"));
stageButtons.forEach((button) => {
  button.addEventListener("click", () => {
    const stage = button.getAttribute("data-set-stage");
    document.getElementById("pv-live").setAttribute("data-stage", stage);
    document.body.setAttribute("data-stage", stage);
    stageButtons.forEach((other) =>
      other.setAttribute("aria-pressed", String(other === button)),
    );
  });
});
const langButtons = Array.from(document.querySelectorAll("[data-set-lang]"));
langButtons.forEach((button) => {
  button.addEventListener("click", () => {
    const lang = button.getAttribute("data-set-lang");
    document.querySelectorAll("[data-lang-block]").forEach((block) => {
      block.hidden = block.getAttribute("data-lang-block") !== lang;
    });
    document.documentElement.lang = lang;
    document.getElementById("pv-live").setAttribute("lang", lang);
    langButtons.forEach((other) =>
      other.setAttribute("aria-pressed", String(other === button)),
    );
  });
});
`;

function galleryBlock(stage: StageName): string {
  return (
    `<section class="pv-block" id="pv-${stage}" data-stage="${stage}" aria-labelledby="pv-${stage}-h">` +
    `<div class="pv-section-head"><h2 id="pv-${stage}-h">${stageHeading(stage)}</h2></div>` +
    `<div class="pv-grid">` +
    `<div class="pv-col" lang="en" data-lang-block="en">${componentColumn("en")}</div>` +
    `<div class="pv-col" lang="zh-Hant" data-lang-block="zh-Hant" hidden>${componentColumn("zh-Hant")}</div>` +
    `</div></section>`
  );
}

